/** One phrase: the theme's, else the plain one, with `{name}` filled in. */
export function t(key, vars = {}) {
  return themeText(key, NODES_TEXT[key] || '').replace(/\{(\w+)\}/g, (m, k) => (k in vars ? String(vars[k]) : m));
}
