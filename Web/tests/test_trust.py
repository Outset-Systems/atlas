def test_the_view_is_admin_only(realm):
    """It is the shortest description of where to aim a forged header, so it
    is gated one step tighter than the map it sits beside."""
    c = realm.app.test_client()
    login_as(c, "alice", PW)
    assert c.get("/api/v2/trust").status_code == 403


