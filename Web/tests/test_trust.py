"""THE TRUST — the view, and the fleet posture it reports.

The last test here is the point of the whole feature. the trust-map generator
encodes what went wrong on 2026-09-09 — four apps that either believed a
forwarded header from anyone who could reach them, or believed nobody and
keyed every caller to the proxy — and bakes its findings into `trust.json`.
Asserting there are no CRITICAL findings turns that from a report you have to
remember to read into a thing the deploy will not let past: the Atlas's own
in-image suite fails, and `deploy-atlas.ps1` recreates nothing.

The generator itself is not imported. `tools/` is not COPYed into the image
(only `Web/`), so a test that imported it would pass on a workstation and
error in the very run that matters. What ships is the JSON, so the JSON is
what is checked.
"""
import json
import os
import sys

import pytest

#: every test here reads trust.json, the lab's own proxy trust map (the trust-map generator),
#: which only the original deployment has
pytestmark = pytest.mark.private_only

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

from appfixture import fresh_app, login_as  # noqa: E402

WEB = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
TRUST_JSON = os.path.join(WEB, "trust.json")

ATLAS_TEST_ENV = {"ATLAS_DATA_BACKEND": "file", "ATLAS_ALLOW_INSECURE": "1",
                  "ATLAS_AUTH_MODE": "standalone"}

PW = "a-long-enough-password"
FORMS = {"addresses", "hop-count", "malformed", "unset"}
LEVELS = {"critical", "warn", "note"}


@pytest.fixture(scope="module")
def trust_map():
    assert os.path.exists(TRUST_JSON), (
        "trust.json is missing — it is generated by the trust-map generator and "
        "baked into the image by `COPY Web/`. Without it THE TRUST answers "
        "503 and the fleet's posture goes unchecked.")
    with open(TRUST_JSON, encoding="utf-8") as fh:
        return json.load(fh)


def test_the_shape_is_what_the_scene_reads(trust_map):
    for key in ("proxies", "apps", "findings", "sources", "generated_by"):
        assert key in trust_map, key
    assert trust_map["sources"], "generated from no config files at all"
    for app in trust_map["apps"]:
        assert app["form"] in FORMS, app
        assert isinstance(app.get("believes"), list)
        assert isinstance(app.get("published"), list)
    for f in trust_map["findings"]:
        assert f["level"] in LEVELS, f
        assert f["app"] and f["text"]


def test_every_proxy_an_app_believes_can_be_named(trust_map):
    """An address with no owner is the dangerous case: it may be a proxy that
    was renumbered, or one that can be handed to another container."""
    unnamed = [(a["name"], b["value"]) for a in trust_map["apps"]
               for b in a["believes"] if not b.get("who")]
    assert not unnamed, f"trusted addresses nobody can account for: {unnamed}"


def test_pinned_proxies_are_actually_pinned(trust_map):
    """Naming a proxy by address is only worth anything if the address cannot
    be handed to something else — the reason tls-proxy and the Hub carry
    ipv4_address in the internal host's compose."""
    internal = [p for p in trust_map["proxies"] if p["address"].startswith("172.")]
    assert internal, "no internal proxy in the map at all"
    assert all(p["pinned"] for p in internal), (
        f"unpinned internal proxy: {[p['name'] for p in internal if not p['pinned']]}")


def test_no_app_counts_hops(trust_map):
    """A hop count believes the header from ANY peer that can open a socket.
    Every app in the suite must name its proxies instead."""
    counters = [a["name"] for a in trust_map["apps"] if a["form"] == "hop-count"]
    assert not counters, f"still counting hops: {counters}"


def test_the_fleet_has_no_critical_finding(trust_map):
    """The gate. A critical finding is a client identity that can be forged;
    shipping the Atlas while one stands would be shipping the report of it."""
    crit = [f"{f['app']}: {f['text']}" for f in trust_map["findings"]
            if f["level"] == "critical"]
    assert not crit, "critical trust findings:\n  " + "\n  ".join(crit)


